// Tracking gate: npm run android:gate [-- --build | --no-build] [-- --mode=video|image] [-- --gpu=host|swiftshader]
// [-- --save-baseline]
// Runs the tracking gate inside the app on emulator-5564 (gate.html): the WebView renders the app's figure in every
// pose and fault, the native plugin's detectImage finds the landmarks and the TypeScript scoring judges them. By
// default detectImage tracks in VIDEO mode, frame to frame with the gate's lead-in, as the live app does;
// `--mode=image` detects every frame afresh. PASS needs 0 criterion failures (so every fault cue comes first) and every
// own-pose score within 5 points of the committed baseline, src/gate/baseline.json. `--save-baseline` replaces the
// baseline with this run. Exits 1 on FAIL. Writes docs/gate-report.md; contact sheets, the full report and the raw
// run go to docs/shots/gate/.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { compare, MAX_DIFF, toBaseline, type Baseline, type Comparison } from '../../src/gate/baseline.ts';
import type { GateRun } from '../../src/gate/criteria.ts';
import type { DetectMode, GateResult, NativeTimings } from '../../src/gate/page.ts';
import { bootEmulator, ensureApk, installApp, lockHarness, startApp, type BuildMode } from './lib/device.ts';
import { adb, APP_ID, AVD, main, median, quantile, ROOT, SERIAL, waitFor } from './lib/tools.ts';

const REPORT = join(ROOT, 'docs/gate-report.md');
const BASELINE = join(ROOT, 'src/gate/baseline.json');
const SHOTS = join(ROOT, 'docs/shots/gate');
const RUN_TIMEOUT_MS = 30 * 60_000;

interface Spread {
  readonly median: number;
  readonly p90: number;
  readonly max: number;
}

interface TimingSummary {
  readonly runS: number;
  readonly frames: number;
  readonly warmupMs: number;
  readonly detectMs: Spread;
  readonly encodeMs: Spread;
  readonly delegates: NativeTimings['delegates'];
}

const spread = (values: readonly number[]): Spread => ({ median: median(values), p90: quantile(values, 0.9), max: Math.max(...values) });
const fmt = (n: number | null | undefined, digits = 1): string => (n === null || n === undefined ? '–' : n.toFixed(digits));

const MODE_TEXT: Record<DetectMode, string> = {
  video:
    'VIDEO mode: every frame carries the gate clock and the landmarker tracks from frame to frame, as live tracking does, ' +
    'with the gate\'s lead-in (5 empty frames, 5 frames of the relaxed stance, then 10 of the pose).',
  image: 'IMAGE mode: every frame is a fresh detection, so the 10 frames of one render give the same landmarks.',
};

function report(o: {
  mode: DetectMode;
  device: string;
  userAgent: string;
  run: GateRun;
  failures: readonly string[];
  comparison: Comparison;
  timings: TimingSummary;
  baseline: Baseline;
  baselineIsThisRun: boolean;
}): string {
  const { run, timings: t, comparison, baseline } = o;
  const off = comparison.cases.filter((c) => !c.ok);
  const webView = /Chrome\/[\d.]+/.exec(o.userAgent)?.[0] ?? o.userAgent;
  const msRow = (name: string, s: Spread) => `| ${name} | ${s.median.toFixed(0)} | ${s.p90.toFixed(0)} | ${s.max.toFixed(0)} |`;
  return [
    '# Tracking gate',
    '',
    'Generated by `npm run android:gate` (`scripts/android/gate.ts`, page `gate.html`, harness `src/gate/`). Do not edit',
    'by hand.',
    '',
    `**Result: ${comparison.passed ? 'PASS' : 'FAIL'}.** ${o.failures.length} criterion failures; ${comparison.cases.length - off.length} of ` +
      `${comparison.cases.length} own-pose scores within ${MAX_DIFF} points of the baseline (largest difference ${comparison.maxDiff.toFixed(1)}).`,
    '',
    '## Run',
    '',
    `- When: ${run.at}.`,
    `- Device: ${o.device}, WebView ${webView}.`,
    `- Figure: \`public/figure\` (the model the app ships), rendered in the WebView by \`${run.backend.renderer}\`${run.backend.software ? ' (software GL)' : ''}.`,
    `- Tracker: the native plugin's \`detectImage\` (MediaPipe Tasks for Android, full model), delegate ${t.delegates.join(' and ')}. Frames ${run.size.join('x')}, ${run.frames} per case, PNG.`,
    `- Detection: ${MODE_TEXT[o.mode]}`,
    `- Baseline: \`${relative(ROOT, BASELINE)}\`, the run of ${baseline.at} (${baseline.mode.toUpperCase()} mode, ${baseline.device})${o.baselineIsThisRun ? ', saved by this run' : ''}. Replace it with \`--save-baseline\`.`,
    ...(baseline.note ? [`- Baseline note: ${baseline.note}`] : []),
    '',
    '## Timings',
    '',
    `Whole run ${t.runS.toFixed(0)} s for ${t.frames} frames. The first \`detectImage\` (it builds the landmarker) took ${t.warmupMs.toFixed(0)} ms.`,
    '',
    '| ms | median | p90 | max |',
    '|---|---|---|---|',
    msRow('`detectImage` round trip (plugin call + detection)', t.detectMs),
    msRow('PNG encode of the frame in the WebView', t.encodeMs),
    '',
    '## Own-pose scores against the baseline',
    '',
    '| case | baseline | run | diff | top cue (baseline) | top cue (run) |',
    '|---|---|---|---|---|---|',
    ...comparison.cases.map((c) =>
      `| ${c.id} | ${fmt(c.baseline.own)} | ${fmt(c.run?.own)} | ${fmt(c.diff)}${c.ok ? '' : ' ✗'} | ${c.baseline.topCue ?? '–'} | ${c.run?.topCue ?? '–'} |`,
    ),
    '',
    '## Criterion failures',
    '',
    ...(o.failures.length === 0 ? ['None.'] : o.failures.map((f) => `- ${f}`)),
    ...(off.length === 0 ? [] : ['', `Own-pose scores more than ${MAX_DIFF} points from the baseline: ${off.map((c) => c.id).join(', ')}.`]),
    '',
    '## Files (git-ignored)',
    '',
    `- \`${relative(ROOT, SHOTS)}/gate-poses.png\`, \`gate-faults.png\`: contact sheets with the native landmarks.`,
    `- \`${relative(ROOT, SHOTS)}/run.json\`: the run, the timings and the landmarks of every case.`,
    `- \`${relative(ROOT, SHOTS)}/full-report.md\`: the full gate report (matrix, faults, reference photos) of this run.`,
    '',
  ].join('\n');
}

const writePng = (path: string, dataUrl: string) => writeFileSync(path, Buffer.from(dataUrl.slice(dataUrl.indexOf(',') + 1), 'base64'));

main(async (cleanup) => {
  const args = process.argv.slice(2);
  const option = (name: string) => args.find((a) => a.startsWith(`--${name}=`))?.slice(name.length + 3);
  const build: BuildMode = args.includes('--build') ? 'always' : args.includes('--no-build') ? 'never' : 'auto';
  const modeOption = option('mode') ?? 'video';
  if (modeOption !== 'video' && modeOption !== 'image') throw new Error(`Unknown --mode=${modeOption}; use video or image.`);
  const mode: DetectMode = modeOption;
  const saveBaseline = args.includes('--save-baseline');
  if (!saveBaseline && !existsSync(BASELINE)) throw new Error(`No baseline at ${relative(ROOT, BASELINE)}. Run with --save-baseline to make one.`);

  const apk = ensureApk(build, ['gate.html']);
  cleanup(lockHarness());
  const gpu = option('gpu') ?? 'host';
  if (gpu !== 'host' && gpu !== 'swiftshader') throw new Error(`Unknown --gpu=${gpu}; use host or swiftshader.`);
  const emulator = await bootEmulator({ camera: 'none', gpu, reuse: true });
  cleanup(() => emulator.stop());
  installApp(apk);
  const device = `${SERIAL} (AVD ${AVD}, Android ${adb('shell', 'getprop', 'ro.build.version.release').trim()}, ${adb('shell', 'getprop', 'ro.product.cpu.abi').trim()}, ${emulator.started ? `-gpu ${gpu}` : 'an emulator that was already running'})`;
  cleanup(() => void adb('shell', 'am', 'force-stop', APP_ID));
  const app = await startApp((type, text) => {
    if (type === 'error' || type === 'warning') console.log(`[app ${type}] ${text}`);
  });
  cleanup(() => app.close());
  await app.open('gate.html');
  await waitFor('window.gate', 60_000, async () => ((await app.cdp.evaluate('typeof window.gate')) === 'object' ? true : undefined));

  console.log(`Running the gate in the app (every frame through detectImage, ${mode.toUpperCase()} mode).`);
  const t0 = Date.now();
  const { output, timings: raw, userAgent } = (await app.cdp.evaluate(`window.gate.run('${mode}')`, RUN_TIMEOUT_MS)) as GateResult;
  const runS = (Date.now() - t0) / 1000;
  const timings: TimingSummary = {
    runS,
    frames: raw.detectMs.length,
    warmupMs: raw.warmupMs,
    detectMs: spread(raw.detectMs),
    encodeMs: spread(raw.encodeMs),
    delegates: raw.delegates,
  };

  const baseline = saveBaseline ? toBaseline(output.run, output.failures, device, mode) : (JSON.parse(readFileSync(BASELINE, 'utf8')) as Baseline);
  if (saveBaseline) writeFileSync(BASELINE, `${JSON.stringify(baseline, null, 1)}\n`);
  const comparison = compare(output.run, output.failures, baseline);

  mkdirSync(SHOTS, { recursive: true });
  writePng(join(SHOTS, 'gate-poses.png'), output.sheet);
  writePng(join(SHOTS, 'gate-faults.png'), output.faultSheet);
  writeFileSync(join(SHOTS, 'full-report.md'), output.report);
  writeFileSync(join(SHOTS, 'run.json'), JSON.stringify({ run: output.run, timings: raw, trace: output.trace }, null, 1));
  writeFileSync(
    REPORT,
    report({ mode, device, userAgent, run: output.run, failures: output.failures, comparison, timings, baseline, baselineIsThisRun: saveBaseline }),
  );

  for (const f of output.failures) console.log(`FAIL ${f}`);
  for (const c of comparison.cases.filter((x) => !x.ok)) console.log(`FAIL ${c.id}: run ${fmt(c.run?.own)}, baseline ${fmt(c.baseline.own)}`);
  console.log(
    `Delegate ${timings.delegates.join('/')}; detectImage median ${timings.detectMs.median.toFixed(0)} ms (p90 ${timings.detectMs.p90.toFixed(0)}); ` +
      `${timings.frames} frames in ${runS.toFixed(0)} s; largest own-pose difference ${comparison.maxDiff.toFixed(1)} (limit ${MAX_DIFF}).`,
  );
  console.log(`Wrote ${relative(ROOT, REPORT)}${saveBaseline ? ` and the baseline ${relative(ROOT, BASELINE)}` : ''}.`);
  console.log(comparison.passed ? 'Tracking gate: PASS' : 'Tracking gate: FAIL');
  return comparison.passed ? 0 : 1;
});
